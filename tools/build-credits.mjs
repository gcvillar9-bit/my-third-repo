#!/usr/bin/env node
/**
 * build-credits (DESIGN 4.2/4.4): public/credits.json and CREDITS.md generated from every
 * assets/manifest/*.json fragment, including the upstream .license sidecar texts recorded by
 * fetch-assets. Needs no network or cache. Re-run after editing a manifest: `pnpm credits`.
 */
import { writeFormatted } from './lib/format.mjs';
import { join } from 'node:path';
import { PUBLIC, ROOT } from './lib/fetch.mjs';
import { listManifests } from './lib/manifest.mjs';

const LICENSES = {
  MIT: { name: 'MIT License', url: 'https://spdx.org/licenses/MIT.html' },
  'CC-BY-3.0': {
    name: 'Creative Commons Attribution 3.0',
    url: 'https://creativecommons.org/licenses/by/3.0/',
  },
  'CC-BY-4.0': {
    name: 'Creative Commons Attribution 4.0',
    url: 'https://creativecommons.org/licenses/by/4.0/',
  },
  'CC-BY-SA-4.0': {
    name: 'Creative Commons Attribution-ShareAlike 4.0',
    url: 'https://creativecommons.org/licenses/by-sa/4.0/',
  },
  'CC-BY-NC-SA-3.0': {
    name: 'Creative Commons Attribution-NonCommercial-ShareAlike 3.0 (non-commercial only)',
    url: 'https://creativecommons.org/licenses/by-nc-sa/3.0/',
  },
  'GPL-2.0-or-later': {
    name: 'GNU General Public License v2.0 or later',
    url: 'https://spdx.org/licenses/GPL-2.0-or-later.html',
  },
  'BSD-3-Clause': { name: 'BSD 3-Clause License', url: 'https://spdx.org/licenses/BSD-3-Clause.html' },
  reference: { name: 'Published reference data (facts, cited)', url: null },
};

function flagsFor(asset) {
  const flags = new Set(asset.flags ?? []);
  if (/\bNC\b|-NC-/.test(asset.license ?? '')) flags.add('non-commercial');
  return [...flags].sort();
}

const entries = [];
for (const m of listManifests()) {
  for (const a of m.assets) {
    entries.push({
      module: m.module,
      id: a.id,
      url: a.url ?? null,
      license: a.license,
      licenseName: LICENSES[a.license]?.name ?? a.license,
      licenseUrl: LICENSES[a.license]?.url ?? null,
      attribution: a.attribution,
      copyright: a.copyright ?? [],
      flags: flagsFor(a),
      note: a.note ?? null,
      outputs: a.outputs ?? [],
      licenseText: a.licenseSidecar?.text ?? null,
    });
  }
}

const credits = {
  version: 1,
  about:
    'Third-party data and imagery used by Cosmos. Generated by tools/build-credits.mjs from assets/manifest/*.json. App code is MIT; data keeps its upstream licence.',
  licenses: LICENSES,
  entries,
};
await writeFormatted(join(PUBLIC, 'credits.json'), JSON.stringify(credits));

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const md = [
  '# Credits',
  '',
  'Generated by `tools/build-credits.mjs` from `assets/manifest/*.json`; do not edit by hand (`pnpm credits`).',
  '',
  'Cosmos application code is MIT licensed. Data and imagery under `public/data` and `public/textures` keep their',
  'upstream licences: derived binaries of CC BY-SA data stay CC BY-SA, and Celestia data stays GPL-2.0-or-later as an',
  'aggregate. Entries flagged **non-commercial** must be replaced (for example by a procedural texture) before any',
  'commercial use.',
  '',
];
for (const module of [...new Set(entries.map((e) => e.module))]) {
  md.push(`## ${module}`, '', '| Source | Licence | Attribution | Used for |', '|---|---|---|---|');
  for (const e of entries.filter((x) => x.module === module)) {
    const src = e.url ? `[${e.id}](${e.url})` : e.id;
    const lic =
      (e.licenseUrl ? `[${e.license}](${e.licenseUrl})` : e.license) +
      (e.flags.includes('non-commercial') ? ' **non-commercial**' : '');
    const attr = [e.attribution, ...e.copyright.map((c) => `© ${c}`)].join('<br>');
    md.push(`| ${esc(src)} | ${esc(lic)} | ${esc(attr)} | ${esc(e.outputs.join(', '))} |`);
  }
  md.push('');
}
const sidecars = entries.filter((e) => e.licenseText);
if (sidecars.length) {
  md.push(
    '## Upstream licence files',
    '',
    'Verbatim copies of the `.license` sidecars shipped next to the source files.',
    '',
  );
  for (const e of sidecars)
    md.push(`### ${e.id}`, '', `Source: ${e.url}.license`, '', '```', e.licenseText, '```', '');
}
await writeFormatted(join(ROOT, 'CREDITS.md'), md.join('\n'));
console.log(
  `credits: ${entries.length} entries (${sidecars.length} licence sidecars) -> public/credits.json, CREDITS.md`,
);
